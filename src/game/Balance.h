// Balance.h - data-driven damage tuning from balance.xml (see docs/BALANCE_XML.md).
//
// balance.xml lets you change, without recompiling:
//   * the damage the player's weapons deal to each enemy (the table in
//     WeaponDamage.cpp), per weapon / per enemy / per playthrough, and
//   * the damage each enemy attack deals to the player (the literals that were
//     scattered across the enemy source files),
// optionally only while a given difficulty mode or add-on is active.
//
// The file is optional: with no balance.xml (or no matching rule) every value is
// exactly the one the source code has.
#ifndef BALANCE_H
#define BALANCE_H

// (Re)read balance.xml. Safe to call again; the title screen calls it so edits are
// picked up without restarting the game.
void Balance_Reload(void);

// Damage the player deals: `dmg` is the table value, the return value is what the
// game should use. weaponSlot is 0..9 (knife, handgun, shotgun, python-DumDum,
// python-magnum, flamethrower, GL explosive, GL acid, GL flame, rocket launcher).
int Balance_WeaponDamage(unsigned int enemyType, unsigned int weaponSlot,
                         int secondPlaythrough, int dmg);

// Damage the player takes from one enemy attack site. `key` is "<Enemy>:<site>"
// (generated by tools/balance_tool.py); `dmg` is the value the code had.
int Balance_EnemyDamage(const char* key, int dmg);

// Wrap the amount at an enemy damage site: BAL_DMG("Hunter:claw", 10)
#define BAL_DMG(key, amount) Balance_EnemyDamage((key), (int)(amount))

#endif // BALANCE_H
